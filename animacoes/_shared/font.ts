export const textWidth = (s: string, scale: number) => s.length * 6 * scale - scale;

function glyphPixels(ch: string): number[][] {
  let base = ch, acc: string | null = null;
  if (MAP[ch]) [base, acc] = MAP[ch];
  const g = G[base];
  const out: number[][] = [];
  if (!g) return out;
  for (let i = 0; i < 35; i++) if (g[i] === '1') out.push([Math.floor(i / 5), i % 5]);
  if (acc) for (const p of ACC[acc]) out.push(p);
  return out;
}

export type TextOpts = {shadow?: string; outline?: string; align?: 'left' | 'center' | 'right'; bold?: boolean};
export function drawText(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, scale: number, color: string, o: TextOpts = {}) {
  s = s.toUpperCase();
  const bw = o.bold ? Math.ceil(scale / 2) : 0;
  const w = textWidth(s, scale) + bw;
  if (o.align === 'center') x = Math.round(x - w / 2);
  else if (o.align === 'right') x = Math.round(x - w);
  const pix: number[][] = [];
  [...s].forEach((ch, i) => glyphPixels(ch).forEach(([r, c]) => pix.push([x + (i * 6 + c) * scale, y + r * scale])));
  if (bw) for (const q of pix.slice()) pix.push([q[0] + bw, q[1]]);
  const plot = (dx: number, dy: number, col: string) => {
    ctx.fillStyle = col;
    for (const [px, py] of pix) ctx.fillRect(px + dx, py + dy, scale, scale);
  };
  const sh = Math.max(1, Math.floor(scale / 2));
  if (o.outline) {
    for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) plot(dx, dy, o.outline);
    if (o.shadow) for (const [dx, dy] of [[sh + 1, sh], [sh, sh + 1]]) plot(dx, dy, o.outline);
  }
  if (o.shadow) plot(sh, sh, o.shadow);
  plot(0, 0, color);
  return w;
}
